jogos = ("Valorant", "Fortnite", "Roblox") #isso é uma tupla (valores fixos)
print("\nTupla:\n")
print(jogos[1])
print("\n--------------------------------------")

#percorrendo a tupla
print("\nPercorrendo a tupla\n")
for jogo in jogos:
    print(jogo)
print("\n--------------------------------------")

#tamanho da tupla
print("\nTamanho da tupla")
print(len(jogos))
print("\n--------------------------------------")